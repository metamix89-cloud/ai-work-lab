def weekly_inquiries(monday, wk):
    """주당 25건. 변질 문의 수는 주마다 고정(보냉재 변경 전 주 2건 안팎 · 뒤 주 9건 안팎)이라 보고서의 '주 2건 → 9건' 이 기록과 맞는다."""
    items = []
    spoil_boost = monday >= SPOIL_RISE
    n = 25
    n_spoil = rng.choice([8, 9, 10]) if spoil_boost else rng.choice([1, 2, 2, 3])
    cats = ["변질"] * n_spoil
    w = {k: v for k, v in BASE_W.items() if k != "변질"}
    cats += rng.choices(list(w), weights=list(w.values()), k=n - n_spoil)
    rng.shuffle(cats)
    for i in range(n):
        cat = cats[i]
        if cat == "변질" and spoil_boost:
            code = rng.choices(["F103", "F105", "F104", "F101"], weights=[14, 9, 4, 2])[0]
        elif cat == "변질":
            code = rng.choices(["F103", "C201", "C203", "F101"], weights=[5, 2, 2, 1])[0]
        elif cat == "알레르기 문의":
            code = rng.choice(["M404", "S501", "M401"])
        else:
            code = rng.choice(list(PROD))
        day = monday + dt.timedelta(days=rng.randint(0, 5))
        name = rng.choice(SURNAMES) + "○○"
        txt = rng.choice(TEXT[cat]).format(p=NAME[code], q=NAME[rng.choice(list(PROD))])
        region = rng.choice(["서울", "경기", "인천", "대전", "대구", "부산", "광주", "전주", "강릉", "제주"])
        if cat == "변질" and spoil_boost and rng.random() < 0.8:
            region = rng.choice(["대구", "부산", "광주", "전주", "강릉", "제주"])
            txt += " (지방이라 이틀 걸려 왔어요)"
        items.append(dict(id="CS-%s-%02d" % (day.strftime("%m%d"), i + 1), date=day.isoformat(), ch=rng.choice(["게시판", "전화", "채팅"]),
                          name=name, region=region, code=code, cat=cat, text=txt, handle=HANDLE[cat]))
    items.sort(key=lambda x: x["date"])
    return items


