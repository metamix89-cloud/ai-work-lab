def W(path, text):
    p = os.path.join(RAW, path)
    os.makedirs(os.path.dirname(p), exist_ok=True)
    with open(p, "w", encoding="utf-8") as f:
        f.write(text.strip() + "\n")
    return path


def plant(pid, path, what):
    PLANTED.append({"id": pid, "file": path, "what": what})


