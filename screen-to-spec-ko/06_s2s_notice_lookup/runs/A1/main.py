def connect():
    conn = sqlite3.connect(DB_PATH)
    conn.row_factory = sqlite3.Row
    return conn


def init_db():
    with closing(connect()) as conn:
        conn.execute(
            """CREATE TABLE IF NOT EXISTS notices (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                category TEXT NOT NULL,
                kind TEXT NOT NULL,
                doc_no TEXT NOT NULL,
                title TEXT NOT NULL,
                posted_at TEXT NOT NULL,
                deadline TEXT,
                department TEXT NOT NULL,
                phone TEXT NOT NULL,
                summary TEXT NOT NULL,
                body TEXT NOT NULL,
                views INTEGER NOT NULL DEFAULT 0
            )"""
        )
        if conn.execute("SELECT COUNT(*) FROM notices").fetchone()[0] == 0:
            conn.executemany(
                """INSERT INTO notices
                   (category, kind, doc_no, title, posted_at, deadline, department, phone, summary, body)
                   VALUES (?,?,?,?,?,?,?,?,?,?)""",
                SEED,
            )
        conn.commit()


@asynccontextmanager
async def lifespan(app: FastAPI):
    init_db()
    yield


app = FastAPI(title="푸른구청 고시·공고", lifespan=lifespan)

LIST_COLS = "id, category, kind, doc_no, title, posted_at, deadline, department, summary, views"


@app.get("/api/categories")
def categories():
    with closing(connect()) as conn:
        counts = {r["category"]: r["n"] for r in conn.execute(
            "SELECT category, COUNT(*) n FROM notices GROUP BY category")}
    return [{"name": c, "count": counts.get(c, 0)} for c in CATEGORIES]


@app.get("/api/notices")
def list_notices(
    category: str | None = None,
    kind: str | None = None,
    q: str | None = Query(None, max_length=100),
    sort: str = Query("latest", pattern="^(latest|views)$"),
    page: int = Query(1, ge=1),
    size: int = Query(8, ge=1, le=50),
):
    where, args = [], []
    if category:
        where.append("category = ?")
        args.append(category)
    if kind:
        where.append("kind = ?")
        args.append(kind)
    if q and q.strip():
        like = f"%{q.strip().replace('%', '').replace('_', '')}%"
        where.append("(title LIKE ? OR summary LIKE ? OR body LIKE ?)")
        args += [like, like, like]
    clause = ("WHERE " + " AND ".join(where)) if where else ""
    order = "views DESC, posted_at DESC" if sort == "views" else "posted_at DESC, id DESC"
    with closing(connect()) as conn:
        total = conn.execute(f"SELECT COUNT(*) FROM notices {clause}", args).fetchone()[0]
        rows = conn.execute(
            f"SELECT {LIST_COLS} FROM notices {clause} ORDER BY {order} LIMIT ? OFFSET ?",
            args + [size, (page - 1) * size],
        ).fetchall()
    return {"total": total, "page": page, "size": size, "items": [dict(r) for r in rows]}


@app.get("/api/notices/{notice_id}")
def get_notice(notice_id: int):
    with closing(connect()) as conn:
        conn.execute("UPDATE notices SET views = views + 1 WHERE id = ?", (notice_id,))
        row = conn.execute("SELECT * FROM notices WHERE id = ?", (notice_id,)).fetchone()
        conn.commit()
    if not row:
        raise HTTPException(404, "해당 고시·공고를 찾을 수 없습니다.")
    return dict(row)


